def show_question():

    global current_question

    if current_question >= len(questions):

        question_label.config(
            text="🎉 Викторина закончена!"
        )

        question_image_label.pack_forget()

        result.config(
            text="Ты ответил(а) на все вопросы!",
            fg="#2E7D32"
        )

        fact_label.config(
            text=""
        )

        fact_image_label.config(
            image=""
        )

        fact_image_label.image = None
        fact_image_label.pack_forget()

        next_button.pack_forget()

        return

    current = questions[current_question]

    # =========================
    # ОЧИЩАЕМ СТАРЫЙ ФАКТ
    # =========================

    fact_label.config(
        text=""
    )

    fact_image_label.config(
        image=""
    )

    fact_image_label.image = None
    fact_image_label.pack_forget()

    # =========================
