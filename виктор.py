def check_answer(answer):

    current = questions[current_question]

    # =========================
    # ПРОВЕРЯЕМ ОТВЕТ
    # =========================

    if answer == current["correct"]:

        result.config(
            text="Правильно! 🎉",
            fg="#2E7D32"
        )

    else:

        result.config(
            text="Неправильно! 😿",
            fg="#C62828"
        )

    # =========================
    # УБИРАЕМ КАРТИНКУ ВОПРОСА
    # =========================

    question_image_label.pack_forget()

    question_image_label.config(
        image=""
    )

    question_image_label.image = None

    # =========================
    # УБИРАЕМ ВАРИАНТЫ ОТВЕТОВ
    # =========================

    for button in answer_buttons:
        button.destroy()

    answer_buttons.clear()

    # =========================
    # ПОКАЗЫВАЕМ ФАКТ
    # =========================

    fact_label.config(
        text=current.get("fact", "")
    )

    # =========================
    # ПОКАЗЫВАЕМ КАРТИНКУ ФАКТА
    # =========================

    image_path = current.get("fact_image")

    if image_path:

        try:

            fact_image = Image.open(
                image_path
            )

            fact_image = fact_image.resize(
                (350, 250)
            )

            fact_photo = ImageTk.PhotoImage(
                fact_image
            )

            fact_image_label.config(
                image=fact_photo
            )

            fact_image_label.image = fact_photo
            fact_image_label.pack(pady=5)

        except FileNotFoundError:

            fact_image_label.config(
                image=""
            )

            fact_image_label.image = None
            fact_image_label.pack_forget()

    else:

        fact_image_label.config(
            image=""
        )

        fact_image_label.image = None
        fact_image_label.pack_forget()

    # =========================
    # ПОКАЗЫВАЕМ "СЛЕДУЮЩИЙ ВОПРОС"
    # =========================

    next_button.pack(pady=15)


